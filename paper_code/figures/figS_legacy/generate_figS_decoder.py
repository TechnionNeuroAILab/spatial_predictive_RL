#!/usr/bin/env python3
"""Produce figS_decoder ("Gaze-alignment decoding") for main_v4_reframed.tex.

Generated by the pre-consolidation script now sitting next to this file as
`analyze_activty_lineardecoder.py`, via its `plot_cross_decoding_results()`.
That is the only generator in the repo that emits the shipped panel: the string
"Gaze-alignment decoding" appears exactly once in the whole repository, in that
file, together with the "Within\\n{period}" / "{a}\\n↓\\n{b}" tick labels and the
grey footer "cross bars: trained on top period, tested on bottom period".

Cross-decoding mode requires BOTH --period and --period_b; the shipped figure
compares the pre-RL frozen-replay period against the post-RL one
(replay_c1_pred vs replay_c1_postrl). The legacy script writes to
`<run_dir>/figures/`; this wrapper copies the PDF to
`figures_supp/figS_decoder_raw.pdf` for `sync_paper_figures.py`.

WARNING -- unverified provenance: `--run_dir` is an inference (the July 2026
invocation was not recorded). Confirm against the shipped PDF before replacing
it in the manuscript. See figures/figS_legacy/README.md.

Requires scikit-learn and seaborn (see paper_code/requirements.txt).

Usage:
    python paper_code/figures/figS_legacy/generate_figS_decoder.py
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
LEGACY = HERE / "analyze_activty_lineardecoder.py"
OUT_DIR = HERE / "figures_supp"

DEFAULT_RUN = REPO / "New_Results_v3" / "final_v11_fixed"
PERIOD_A = "replay_c1_pred"
PERIOD_B = "replay_c1_postrl"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run_dir", type=str, default=str(DEFAULT_RUN))
    ap.add_argument("--period", type=str, default=PERIOD_A)
    ap.add_argument("--period_b", type=str, default=PERIOD_B)
    ap.add_argument("--dry_run", action="store_true",
                    help="print the legacy invocation without running it")
    args = ap.parse_args()

    run_dir = Path(args.run_dir)
    for period in (args.period, args.period_b):
        needed = run_dir / "data" / f"df_activations_{period}.pkl"
        if not needed.exists():
            print(f"ERROR: missing {needed}")
            return 1

    cmd = [sys.executable, str(LEGACY),
           "--run_dir", str(run_dir),
           "--period", args.period,
           "--period_b", args.period_b]
    print("running:", " ".join(cmd))
    if args.dry_run:
        return 0
    subprocess.run(cmd, check=True, cwd=str(HERE))

    produced = run_dir / "figures" / \
        f"linear_decoder_cross_{args.period}_vs_{args.period_b}.pdf"
    if not produced.exists():
        print(f"ERROR: legacy script finished but {produced} is absent")
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    dest = OUT_DIR / "figS_decoder_raw.pdf"
    shutil.copy2(produced, dest)
    print(f"figS_decoder_raw.pdf  <-  {produced.relative_to(REPO)}")
    print(f"wrote {dest.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
